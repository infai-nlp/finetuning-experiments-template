from pathlib import Path
import click
from .config import load_cfg
from .utils import prepare_paths


@click.group(context_settings=dict(help_option_names=["-h", "--help"], color=True))
def cli():
    """LLM fine‑tuning CLI (training / inference / evaluation)."""
    pass


# --------------------- train entrypoint -------------------------------------- #
@cli.command("train")
@click.option(
    "--config",
    "config_file",
    type=click.Path(exists=True, dir_okay=False),
    required=True,
    help="Path to YAML configuration file",
)
def train(config_file):
    """Fine‑tune a base model according to a CONFIG YAML."""
    from .train import run_training

    cfg = load_cfg(Path(config_file))
    cfg = prepare_paths(cfg)
    run_training(cfg)


# --------------------- inference entrypoint --------------------------------- #
@cli.command("inference")
@click.option(
    "--config",
    "config_file",
    type=click.Path(exists=True, dir_okay=False),
    required=True,
    help="Path to YAML configuration file",
)
@click.option(
    "--adapter/--no-adapter",
    "lora_adapter",
    default=False,
    help="Use LoRA adapter (default: baseline model).",
)
def inference(config_file, lora_adapter):
    """Evaluate the model on the given dataset."""
    from .inference import run_inference

    cfg = load_cfg(Path(config_file))
    cfg = prepare_paths(cfg)
    run_inference(cfg, lora_adapter)


# # --------------------- evaluation entrypoint --------------------------------------- #
# Info:
# task: This uses the predictions (base and/or lora) generated by the inference step, that were stored according to the prepare_paths (utils.py) function.
@cli.command(
    name="evaluation",
    help="""
Run one or more evaluation tasks sequentially with the selected adapter
mode.

Examples:

    # Run evaluations as specified in config with both base and LoRA models. Continue on errors and print verbose output: \n
        llm-cli evaluate --config configs/my_model.yaml --task --adapter-mode both --keep-going --verbose

""",
)
@click.option(
    "--config",
    "config_file",
    type=click.Path(exists=True, dir_okay=False),
    required=True,
    help="Path to YAML configuration file",
)
@click.option(
    "--task/--no-task",
    default=False,
    help="Run Evaluation on task.",
)
@click.option(
    "--adapter-mode",
    type=click.Choice(["no-adapter", "adapter", "both"], case_sensitive=False),
    default="both",
    show_default=True,
    help="Run Base (no-adapter), LoRA (adapter), or both for every selected task.",
)
@click.option(
    "--stop-on-error/--keep-going",
    default=True,
    show_default=True,
    help="Stop on first error or continue with other evaluations.",
)
@click.option("--verbose", is_flag=True, help="Print full tracebacks on errors.")
def eval_cmd(
    config_file,
    task: bool,
    adapter_mode: str,
    stop_on_error: bool,
    verbose: bool,
):
    """Run one or more evaluation tasks sequentially with the selected adapter mode."""

    from .evaluation import run_eval  # our-task

    config = prepare_paths(load_cfg(Path(config_file)))
    click.secho(f"CONFIG:\n {config}", fg="blue")

    tasks = []
    if task:
        tasks.append(("Task", run_eval))

    if not tasks:
        raise click.UsageError(
            "No evaluations selected."
        )

    # Expand tasks per adapter-mode
    evaluations = []
    for name, fn in tasks:
        if adapter_mode in ("no-adapter", "both"):
            evaluations.append((f"{name} (base)", fn, False))
        if adapter_mode in ("adapter", "both"):
            evaluations.append((f"{name} (lora)", fn, True))

    click.secho("Selected evaluations:", fg="blue")
    for name, _, adapter in evaluations:
        click.secho(f"  - {name}", fg="blue")

    # Run sequentially
    for name, fn, adapter in evaluations:
        try:
            fn(config, adapter)
        except Exception as exc:
            click.secho(f"[ERROR] {name} failed: {exc}", fg="red", err=True)
            if verbose:
                import traceback
                traceback.print_exc()
            if stop_on_error:
                raise click.ClickException(f"Evaluation '{name}' failed.") from exc
            click.secho("Continuing due to --keep-going…", fg="yellow", err=True)


if __name__ == "__main__":
    cli()
